# ============================================================
# 보조 평가지표: RMSE 및 MAE
# ============================================================
#
# [현재 보고서와의 관계]
# - 중간보고서의 핵심 평가지표는 Spearman Rank IC이다.
# - RMSE와 MAE는 현재 확정된 후보 선택 기준이 아니다.
# - 필요하면 보조 진단 지표로 추가할 것을 제안한다.
#
# RMSE: Root Mean Squared Error
# - 실제 수익률과 예측 수익률의 제곱오차 평균에
#   제곱근을 취한 값이다.
# - 값이 작을수록 수익률 예측오차가 작다는 뜻이다.
# - 큰 예측오차에 상대적으로 민감하다.
#
# MAE: Mean Absolute Error
# - 실제 수익률과 예측 수익률의 절대오차 평균이다.
# - 값이 작을수록 평균적인 절대 예측오차가 작다는 뜻이다.
#
# [왜 보조 지표로 사용하는가?]
# - Rank IC는 종목 간 상대순위를 평가한다.
# - RMSE와 MAE는 예측 수익률 자체의 오차를 평가한다.
# - 순위는 잘 맞히지만 수익률 크기는 부정확한 경우를
#   추가로 파악하기 위해 사용한다.
#
# [적용 원칙]
# - OLS, Ridge, MLP에 동일한 기준으로 계산한다.
# - 동일한 예측값, 실제값, 평가 표본을 활용한다.
# - 월별 계산 및 집계 방식을 사전에 통일한다.
# - 추가한다고 해도 기본 후보 선택 기준은 Rank IC로 유지한다.
# - RMSE/MAE를 보고 후보를 다시 선택하려면
#   연구계획 변경과 사전 선택 규칙 정의가 필요하다.
#
#
# ============================================================
# 2차 실험: 활성화 함수 × Optimizer
# ============================================================
#
# [상태]
# - 후속 민감도 분석 제안이며 확정 실험은 아니다.
#
# [연구 질문]
# - 1차 성능이 ReLU/Adam이라는 초기 설정에 의존하는가?
# - 활성화 함수가 달라지면 Rank IC도 달라지는가?
# - 최적화 알고리즘이 달라지면 수렴과 예측력이 달라지는가?
#
# [비교 설계]
# - 1차에서 선택한 은닉층과 alpha를 우선 고정한다.
# - 활성화 함수 2종 × Optimizer 2종을 비교한다.
#
# - B1: ReLU + Adam (1차 기준선)
# - B2: Tanh + Adam
# - B3: ReLU + SGD
# - B4: Tanh + SGD
#
# [왜 Tanh인가?]
# - ReLU와 서로 다른 비선형 변환 특성을 갖는다.
# - Tanh는 출력이 -1~1 범위이며 양수·음수 출력을 갖는다.
# - 큰 입력에서 기울기가 작아지는 포화 특성도 있다.
# - 이러한 차이가 H1/H3의 비선형관계 학습에
#   도움이 되는지 확인한다.
# - Tanh가 더 좋다고 미리 가정하지 않는다.
#
# [왜 SGD인가?]
# - Adam은 적응적인 가중치 업데이트를 사용한다.
# - SGD는 기울기 기반의 다른 업데이트 방식을 사용한다.
# - 최적화 방식에 따른 수렴과 Rank IC 차이를 확인한다.
#
# [SGD 비교 시 주의]
# - SGD와 Adam의 적절한 학습률은 다를 수 있다.
# - SGD의 학습률과 모멘텀 등 주요 설정을 사전에 정의한다.
# - 수렴하지 않은 SGD를 그대로 비교해
#   알고리즘 자체가 열등하다고 결론 내리지 않는다.
# - SGD의 학습률 후보를 추가하면 실제 실험 건수는
#   기본 4개 조합보다 증가할 수 있다.
#
# [통제]
# - 동일한 H1/H3 데이터, 공통 표본, Fold를 사용한다.
# - 핵심 지표는 동일한 평균 월별 Rank IC이다.
# - 손실함수는 squared_error로 유지한다.
# - Dropout은 사용하지 않는다.
# - 수렴 상태, Epoch 및 실행 시간을 함께 기록한다.
# - 후보와 동률 규칙을 추가 실험 전에 확정한다.
#
#
# ============================================================
# 3차 실험: 학습 안정성·과적합·강건성 검증
# ============================================================
#
# [상태]
# - 조건부 후속 실험이며 모든 항목이 필수인 것은 아니다.
#
# [연구 질문]
# - 선택 결과가 특정 학습률이나 배치 크기에 의존하는가?
# - 500 Epoch이라는 반복 상한이 적절한가?
# - 초기 난수 시드가 달라져도 Rank IC가 안정적인가?
# - 과적합을 줄이는 추가 방법이 필요한가?
# - 극단적인 수익률 오차가 학습에 과도한 영향을 주는가?
# - 순위 자체를 학습하면 Rank IC가 개선될 가능성이 있는가?
#
#
# ------------------------------------------------------------
# 3-1. Learning Rate
# ------------------------------------------------------------
#
# 제안 후보:
# - Adam: 0.0003 / 0.001 / 0.003
# - SGD:  0.001 / 0.01
#
# 이유:
# - 가중치 업데이트 크기에 따른 수렴 속도와 안정성을 확인.
# - 손실 진동, 수렴 정체, 검증 Rank IC를 비교한다.
# - 각 Optimizer의 특성을 고려하여 별도 조정한다.
#
#
# ------------------------------------------------------------
# 3-2. Batch Size
# ------------------------------------------------------------
#
# 제안 후보:
# - 128 / 256 / 512
#
# 이유:
# - 배치 크기에 따른 기울기 변동과 학습 안정성 확인.
# - 연산 비용과 예측 성능의 차이를 비교한다.
#
#
# ------------------------------------------------------------
# 3-3. 최대 Epoch
# ------------------------------------------------------------
#
# 제안 후보:
# - 200 / 500 / 1000
#
# 이유:
# - 500 Epoch 상한이 부족하거나 과도한지 확인한다.
# - 실제 반복 횟수와 수렴 여부를 함께 판단한다.
# - 반복 횟수가 많다고 검증 성능이 좋아지는 것은 아니다.
#
#
# ------------------------------------------------------------
# 3-4. Random State
# ------------------------------------------------------------
#
# 제안 후보:
# - 42 / 123 / 2026
#
# 이유:
# - 초기 가중치에 따른 성능 변동을 확인한다.
# - 특정 시드에서만 높은 Rank IC가 나오는지 점검한다.
# - 시드별 평균 성능 및 변동성을 함께 기록한다.
#
# 주의:
# - 시드 자체를 고르는 과정에서도 선택 편향이 생길 수 있다.
# - 시드 비교는 강건성 진단을 우선 목적으로 한다.
#
#
# ------------------------------------------------------------
# 3-5. Shuffle
# ------------------------------------------------------------
#
# 제안 후보:
# - False / True
#
# 이유:
# - 미니배치 순서 변경에 따른 수렴과 예측 성능을 확인한다.
#
# 주의:
# - Train/Validation의 시간순 분리는 그대로 유지한다.
# - Shuffle 비교와 미래정보 누수 여부를 혼동하지 않는다.
#
#
# ------------------------------------------------------------
# 3-6. Early Stopping
# ------------------------------------------------------------
#
# 비교 대상:
# - 현재 설정: early_stopping=False
# - 추가 대안: 학습기간 내부의 시간순 조기종료 절차
#
# 이유:
# - 불필요한 반복을 줄이고 과적합을 완화할 수 있는지 확인.
# - 조기종료가 Rank IC 및 안정성에 미치는 영향을 확인한다.
#
# 주의:
# - scikit-learn 내장 Early Stopping을 단순히 True로 바꾸는
#   방식은 시간순 Rank IC 기준과 일치하지 않는다.
# - 학습 Fold 내부에서 별도의 시간순 검증을 설계해야 한다.
# - 외부 검증연도와 Test는 조기종료 판단에 사용하지 않는다.
#
#
# ------------------------------------------------------------
# 3-7. Loss Function
# ------------------------------------------------------------
#
# 현재 기준선:
# - squared_error (MSE 기반 제곱오차 손실)
#
# 조건부 검토 대안:
# - Huber Loss
# - Pairwise Ranking Loss
# - Listwise Ranking Loss
#
# [왜 Huber Loss인가?]
# - 제곱오차 손실은 큰 오차를 제곱하여 벌점을 부여한다.
# - 주식 수익률의 극단값이 학습에 큰 영향을 줄 수 있다.
# - Huber는 큰 오차에 대한 민감도를 완화할 수 있다.
# - 극단값에 대한 강건성이 Rank IC를 개선하는지 확인한다.
#
# [왜 Ranking Loss인가?]
# - 현재 연구의 핵심 목적은 종목 간 차월 수익률 순위 예측이다.
# - MSE는 수익률의 수치적 오차를 줄이도록 학습한다.
# - Ranking Loss는 종목 간 상대순위를 학습하도록 설계한다.
# - 학습 목적과 Rank IC 평가 목적의 정합성을 확인하기 위해
#   후속 대안으로 검토한다.
#
# [Pairwise Ranking Loss]
# - 동일 목표월의 두 종목을 비교한다.
# - 실제 수익률이 높은 종목의 예측 점수도
#   더 높아지도록 학습한다.
# - 종목쌍의 순서 오류에 벌점을 부여하는 방식이다.
#
# [Listwise Ranking Loss]
# - 동일 목표월의 여러 종목을 하나의 집합으로 고려한다.
# - 전체 종목 순위의 품질을 개선하도록 학습한다.
# - 구체적인 손실 정의와 표본 구성 규칙이 별도로 필요하다.
#
# [중요한 제약]
# - Ranking Loss가 Spearman Rank IC와 정확히 같은 것은 아니다.
# - Ranking Loss를 사용한다고 Rank IC 향상이 보장되지는 않는다.
# - 현재 scikit-learn MLPRegressor에서는 Huber나
#   Ranking Loss를 단순 옵션 변경으로 적용할 수 없다.
# - 필요하면 별도 프레임워크 및 학습 절차를 구현한다.
# - Ranking Loss의 종목 비교는 동일 목표월 내부로 제한한다.
# - 미래 목표월 정보를 학습에 사용하지 않는다.
#
#
# ------------------------------------------------------------
# 3-8. Dropout
# ------------------------------------------------------------
#
# 현재 기준선:
# - Dropout 미사용, L2 규제 사용.
#
# 제안 후보:
# - dropout_rate=0.1
# - dropout_rate=0.2
#
# 이유:
# - 학습 과정에서 일부 뉴런 출력을 무작위로 비활성화해
#   특정 뉴런에 대한 과도한 의존을 줄일 수 있다.
# - L2 규제만 사용한 기준선보다 과적합을
#   더 잘 완화하는지 검토한다.
#
# 주의:
# - Dropout은 과적합을 반드시 해결하는 방법은 아니다.
# - 너무 강한 Dropout은 과소적합을 유발할 수 있다.
# - scikit-learn MLPRegressor는 Dropout을 기본 지원하지 않는다.
# - PyTorch 등 별도 구현이 필요하다.
# - 프레임워크를 바꾸는 경우 기존 Dropout 없는 기준모형도
#   재구현하여 구현체 차이를 Dropout 효과로 오인하지 않는다.
#
#
# ------------------------------------------------------------
# 3-9. 추가 Optimizer: L-BFGS
# ------------------------------------------------------------
#
# 조건부 검토:
# - Adam / SGD 외에 L-BFGS를 추가할 수 있다.
#
# 이유:
# - 미니배치 기반 방법과 다른 최적화 특성을 비교한다.
# - 데이터 규모 및 수렴 특성에 따라 유리할 가능성이 있다.
#
# 주의:
# - L-BFGS는 미니배치 방식이 아니다.
# - batch_size 및 learning_rate_init을 Adam/SGD와
#   동일한 의미의 실험 변수로 사용하지 않는다.
# - 반복 횟수도 Optimizer별 정의를 구분해 기록한다.
#
#
# ============================================================
# 3차 실험의 실행 원칙
# ============================================================
#
# - 위의 모든 후보를 한 번에 전수 조합하지 않는다.
# - 1·2차의 수렴 상태, Rank IC, 학습 손실 등을 확인한다.
# - 관찰된 문제에 대응하는 항목을 우선 선택한다.
#
# 예시:
# - 수렴하지 않음:
#   학습률, Epoch 상한, Optimizer 설정 검토.
#
# - 학습 손실은 감소하지만 검증 Rank IC가 낮음:
#   과적합 여부, 규제강도, 조기종료 등을 검토.
#
# - 시드마다 성능 변동이 큼:
#   다중 시드 안정성 검증.
#
# - 일부 극단적 수익률이 손실에 큰 영향을 줌:
#   Huber Loss 검토.
#
# - 수익률의 크기 예측보다 순위 학습에 집중할 필요:
#   Ranking Loss 검토.
#
# - 복잡한 신경망에서 과적합 문제가 지속됨:
#   Dropout 등 추가 규제 검토.
#
# - 모든 조건부 실험은 추가 후보와 변경 근거를
#   실행하기 전에 문서화한다.
# - 추가 후보 선택 기준과 동률 규칙도 사전에 정의한다.
# - 같은 검증기간을 반복 탐색해 생기는 선택 편향을 고려한다.
#
#
# ============================================================
# 전체 실험의 데이터 누수 방지 및 비교 원칙
# ============================================================
#
# [시간 구분]
# - Warm-up: 2000년
# - Train 및 내부 검증: 2001~2021년
# - 최종 Test: 2022~2025년
#
# [PIT 및 전처리]
# - 기준월 t 말까지 실제 이용 가능한 정보만 사용한다.
# - 차월 수익률이나 사후 공시정보를 특징 계산에 사용하지 않는다.
# - Fold별 전처리 변환기는 해당 Fold의 학습자료로만 적합한다.
# - 검증자료의 목표값을 변환기 적합에 사용하지 않는다.
#
# [공통 평가]
# - H1/H3 공통 표본을 사용한다.
# - OLS, Ridge, MLP의 평가기간과 대상 종목을 일치시킨다.
# - 동일한 Rank IC 정의와 공통 유효월을 사용한다.
# - Rank IC 계산 불가능 월을 임의로 0 처리하지 않는다.
# - RMSE/MAE를 추가하면 동일 표본에서 보조적으로 계산한다.
#
# [추가 탐색의 선택 편향]
# - 1차 결과를 본 후 같은 검증기간으로 2·3차 설정을
#   반복적으로 선택하면 검증기간에 과적합할 수 있다.
# - 후속 실험 전 후보 범위와 선택 기준을 명시한다.
# - 필요하면 Train 기간 내부에서 설정 선택용 기간과
#   별도 확인용 기간을 사전에 구분한다.
# - 이러한 별도 확인기간은 기존 Expanding Window
#   평가와의 관계까지 정의한 후 적용한다.
#
# [재현성]
# - 후보별 설정값을 config 및 실험 이력에 기록한다.
# - 실행 환경과 라이브러리 버전을 기록한다.
# - 시드, 수렴 상태, 실제 Epoch, 손실 및 Rank IC를 기록한다.
# - 실험 결과가 나오기 전 성능 우위를 단정하지 않는다.
#
